import { Lesson, LessonStatus } from "@/types/learning";

interface LessonSeed {
  id: string;
  unitId: string;
  languageId: string;
  lessonNumber: number;
  title: string;
  description: string;
  status: LessonStatus;
  icon: string;
  targetLanguage: string;
  teacherName: string;
  city: string;
  goals: string[];
  word: string;
  translation: string;
  phonetic: string;
  exampleSentence: string;
  exampleTranslation: string;
  phrase: string;
  phraseTranslation: string;
  quizOptions: [string, string, string, string];
}

function buildLesson(seed: LessonSeed): Lesson {
  return {
    id: seed.id,
    unitId: seed.unitId,
    languageId: seed.languageId,
    lessonNumber: seed.lessonNumber,
    title: seed.title,
    description: seed.description,
    status: seed.status,
    xpReward: 15,
    estimatedMinutes: 5,
    icon: seed.icon,
    goals: seed.goals,
    vocabulary: [
      {
        id: `${seed.id}-v1`,
        word: seed.word,
        translation: seed.translation,
        phonetic: seed.phonetic,
        partOfSpeech: "phrase",
        exampleSentence: seed.exampleSentence,
        exampleTranslation: seed.exampleTranslation,
      },
    ],
    phrases: [
      {
        id: `${seed.id}-p1`,
        phrase: seed.phrase,
        translation: seed.phraseTranslation,
        phonetic: seed.phonetic,
      },
    ],
    activities: [
      {
        id: `${seed.id}-a1`,
        type: "multiple_choice",
        prompt: `Choose the meaning of "${seed.word}":`,
        question: seed.word,
        options: seed.quizOptions,
        correctAnswer: seed.translation,
        explanation: `"${seed.word}" means "${seed.translation}" in ${seed.targetLanguage}.`,
      },
    ],
    aiTeacherPrompt: {
      systemPrompt: `You are ${seed.teacherName}, a friendly ${seed.targetLanguage} AI tutor in ${seed.city}. Guide the student to practice "${seed.word}" and "${seed.phrase}".`,
      welcomeMessage: `Welcome! Let's practice ${seed.title.toLowerCase()} in ${seed.targetLanguage}. Try saying: "${seed.word}"!`,
      scenario: `${seed.title} in ${seed.city}.`,
      targetLanguage: seed.targetLanguage,
      keyPhrasesToElicit: [seed.word, seed.phrase],
      feedbackCriteria: ["Clear pronunciation", "Natural polite phrasing"],
    },
  };
}

